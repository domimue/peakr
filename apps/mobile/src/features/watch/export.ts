import {
  cumulativeDistances,
  decodePolyline,
  type ElevationPoint,
  type Workout,
} from '@peakr/engine';
import {
  encodeWorkoutFit,
  routeToGpx,
  toWatchWorkouts,
  type NotExportable,
  type WatchContext,
  type WatchRoute,
  type WatchWorkout,
} from '@peakr/watch';

import { supabase } from '@/data/supabase';
import { shareFile, type SharedFile } from '@/features/sharing/share-file';

export { shareFile };
export type WatchFile = SharedFile;

/**
 * File export, the universal fallback for every watch brand (CLAUDE.md "Watch integrations"): a
 * structured .FIT workout and the chosen route as a .GPX course, saved and shared from the phone
 * so the user can import them into Garmin Connect, the COROS or Suunto app and so on.
 *
 * The FIT file is written on the device with Garmin's official FIT JavaScript SDK. Should the
 * runtime not be able to encode it (the SDK needs TextEncoder / DataView features that not every
 * JS engine build has), the same file is generated by the Edge Function `watch/export`.
 */

export const FIT_MIME = 'application/vnd.ant.fit';
export const GPX_MIME = 'application/gpx+xml';

const slug = (text: string) =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 40) || 'workout';

export type WorkoutFiles =
  | { ok: true; workouts: WatchWorkout[]; files: WatchFile[]; source: 'device' | 'server' }
  | { ok: false; reason: NotExportable | 'encode_failed' };

function fromBase64(base64: string): Uint8Array {
  return Uint8Array.from(atob(base64), (c) => c.charCodeAt(0));
}

interface ExportFile {
  name: string;
  mime: string;
  base64: string;
}

/** Same files from the Edge Function (used when the device cannot encode them). */
async function serverFiles(body: {
  workouts?: WatchWorkout[];
  route?: WatchRoute;
}): Promise<WatchFile[] | null> {
  if (!supabase) return null;
  const { data, error } = await supabase.functions.invoke<{ files: ExportFile[] }>('watch/export', {
    body,
  });
  if (error || !data) return null;
  return data.files.map((f) => ({ name: f.name, mime: f.mime, bytes: fromBase64(f.base64) }));
}

/** The FIT workout file(s) of a plan workout (a brick gives one file per sport). */
export async function workoutFiles(w: Workout, ctx: WatchContext): Promise<WorkoutFiles> {
  const converted = toWatchWorkouts(w, ctx);
  if (!converted.ok) return converted;
  try {
    const files = converted.workouts.map((watch) => ({
      name: `${watch.date}-${slug(watch.name)}.fit`,
      mime: FIT_MIME,
      bytes: encodeWorkoutFit(watch),
    }));
    return { ok: true, workouts: converted.workouts, files, source: 'device' };
  } catch (e) {
    console.warn('FIT encoding on the device failed, using the server', String(e));
    const files = await serverFiles({ workouts: converted.workouts });
    return files
      ? { ok: true, workouts: converted.workouts, files, source: 'server' }
      : { ok: false, reason: 'encode_failed' };
  }
}

function elevationAt(profile: readonly ElevationPoint[], distanceM: number): number | null {
  const first = profile[0];
  if (!first) return null;
  let prev = first;
  for (const p of profile) {
    if (p.distanceM >= distanceM) {
      const span = p.distanceM - prev.distanceM;
      if (span <= 0) return p.elevationM;
      return (
        prev.elevationM + ((p.elevationM - prev.elevationM) * (distanceM - prev.distanceM)) / span
      );
    }
    prev = p;
  }
  return prev.elevationM;
}

/** A library route as a watch route: coordinates from the polyline, elevation from the profile. */
export function watchRouteOf(route: {
  id: string;
  name: string;
  sport: 'run' | 'bike';
  polyline: string;
  profile: readonly ElevationPoint[];
}): WatchRoute {
  const points = decodePolyline(route.polyline);
  const distances = cumulativeDistances(points);
  return {
    id: route.id,
    name: route.name,
    sport: route.sport,
    points: points.map((p, i) => {
      const ele = elevationAt(route.profile, distances[i] ?? 0);
      return { lat: p.lat, lon: p.lon, ele: ele === null ? null : Math.round(ele * 10) / 10 };
    }),
  };
}

export function routeFile(route: WatchRoute): WatchFile {
  return {
    name: `${slug(route.name)}.gpx`,
    mime: GPX_MIME,
    bytes: new TextEncoder().encode(routeToGpx(route)),
  };
}
