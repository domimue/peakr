import { colors } from '@peakr/theme';
import type { Metadata, Viewport } from 'next';
import { Archivo } from 'next/font/google';
import localFont from 'next/font/local';

import { SiteFooter } from '@/components/site-footer';
import { SiteHeader } from '@/components/site-header';
import { messages } from '@/i18n';
import { siteUrl } from '@/lib/site';

import './globals.css';

// next/font self-hosts the fonts at build time – no requests to Google from visitors.
// Body and UI: Archivo 400–500 at width 100 % (variable font incl. the width axis).
const archivo = Archivo({
  variable: '--font-archivo',
  subsets: ['latin'],
  axes: ['wdth'],
  display: 'swap',
});

// Headlines: the same static instance the app uses (Archivo 800, width 112 %).
const peakrDisplay = localFont({
  src: '../../../../packages/theme/fonts/Peakr-Display.ttf',
  variable: '--font-peakr-display',
  weight: '800',
  display: 'swap',
});

const t = messages.meta;

const APP_STORE_ID = process.env.NEXT_PUBLIC_APP_STORE_ID?.match(/^\d+$/)?.[0] ?? null;

export const metadata: Metadata = {
  metadataBase: new URL(siteUrl()),
  title: { default: t.title, template: `%s | ${t.siteName}` },
  description: t.description,
  applicationName: t.siteName,
  alternates: { canonical: '/' },
  openGraph: {
    type: 'website',
    siteName: t.siteName,
    locale: 'en',
    title: t.title,
    description: t.description,
    url: '/',
  },
  twitter: { card: 'summary_large_image', title: t.title, description: t.description },
  robots: { index: true, follow: true },
  // Generated by `pnpm brand:assets`; favicon.ico and opengraph-image.png live in src/app.
  icons: {
    icon: [{ url: '/favicon.svg', type: 'image/svg+xml' }],
    apple: { url: '/apple-touch-icon.png', sizes: '180x180' },
  },
  manifest: '/manifest.webmanifest',
  // iOS Smart App Banner, once the app is in the App Store (NEXT_PUBLIC_APP_STORE_ID, the numeric
  // id from the App Store URL). Safari shows "Open" instead of "Get" when Peakr is installed.
  ...(APP_STORE_ID ? { itunes: { appId: APP_STORE_ID } } : {}),
};

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  themeColor: colors.ink,
};

export default function RootLayout({ children }: LayoutProps<'/'>) {
  return (
    <html lang="en" className={`${archivo.variable} ${peakrDisplay.variable} h-full antialiased`}>
      <body className="flex min-h-full flex-col">
        <SiteHeader />
        <div id="content" className="flex flex-1 flex-col">
          {children}
        </div>
        <SiteFooter />
      </body>
    </html>
  );
}
