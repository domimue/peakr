/**
 * Generates every brand asset from the "Pulse Peak" mark and the Peakr-Display font:
 * wordmark (TS + SVG, from assets/wordmark.json), app icon, Android adaptive icon, splash, favicons, PWA icons and OG image.
 * Run with `pnpm brand:assets`. Never edit the outputs by hand.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { colors, lockupProportions, mark } from '@peakr/theme';
import { Resvg } from '@resvg/resvg-js';
import pngToIco from 'png-to-ico';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
const out = (path: string) => resolve(root, path);

const round = (n: number) => Math.round(n * 100) / 100;

// ---------------------------------------------------------------------------------------------
// Wordmark: outlined by packages/theme/scripts/make-display-font.py (fontTools + HarfBuzz kerning).

interface Wordmark {
  fontSize: number;
  width: number;
  height: number;
  path: string;
}

const wordmark = JSON.parse(
  readFileSync(out('packages/theme/assets/wordmark.json'), 'utf8'),
) as Wordmark;
if (wordmark.fontSize !== lockupProportions.fontSize) {
  throw new Error('wordmark.json must be outlined at the lockup font size');
}

writeFileSync(
  out('packages/theme/src/logo.generated.ts'),
  `// Generated by \`pnpm brand:assets\` (tools/brand-assets) from fonts/Peakr-Display.ttf – do not edit.\n` +
    `export const wordmark = {\n` +
    `  fontSize: ${wordmark.fontSize},\n` +
    `  width: ${wordmark.width},\n` +
    `  height: ${wordmark.height},\n` +
    `  path: '${wordmark.path}',\n` +
    `} as const;\n`,
);

// ---------------------------------------------------------------------------------------------
// SVG builders

/** Visible extent of the mark in its 120 box incl. round caps (stroke 10 → ±5). */
const MARK_BOX = { x1: 1, y1: 17, x2: 119, y2: 97 };
const MARK_VISIBLE_WIDTH = MARK_BOX.x2 - MARK_BOX.x1;

function markElement(color: string, transform = '') {
  return (
    `<polyline${transform ? ` transform="${transform}"` : ''} points="${mark.points}" fill="none" ` +
    `stroke="${color}" stroke-width="${mark.strokeWidth}" stroke-linecap="round" stroke-linejoin="round"/>`
  );
}

/** Mark optically centred in a square canvas, visible width = widthRatio × size. */
function markOnCanvas(size: number, color: string, widthRatio: number, bg?: string, radius = 0) {
  const s = (widthRatio * size) / MARK_VISIBLE_WIDTH;
  const cx = (MARK_BOX.x1 + MARK_BOX.x2) / 2;
  const cy = (MARK_BOX.y1 + MARK_BOX.y2) / 2;
  const tx = round(size / 2 - cx * s);
  const ty = round(size / 2 - cy * s);
  const background = bg
    ? `<rect width="${size}" height="${size}" rx="${radius}" fill="${bg}"/>`
    : '';
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">` +
    background +
    markElement(color, `translate(${tx} ${ty}) scale(${round(s * 1000) / 1000})`) +
    `</svg>`
  );
}

function wordmarkSvg(color: string) {
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${wordmark.width} ${wordmark.height}">` +
    `<path d="${wordmark.path}" fill="${color}"/></svg>`
  );
}

/** Lockup group: mark 64 / gap 14 / wordmark at font size 50, vertically centred, origin top-left. */
function lockupGroup(markColor: string, wordColor: string) {
  const { mark: markSize, gap } = lockupProportions;
  const height = Math.max(markSize, wordmark.height);
  const width = markSize + gap + wordmark.width;
  const markScale = markSize / mark.viewBox;
  const body =
    markElement(markColor, `translate(0 ${round((height - markSize) / 2)}) scale(${markScale})`) +
    `<path transform="translate(${markSize + gap} ${round((height - wordmark.height) / 2)})" d="${wordmark.path}" fill="${wordColor}"/>`;
  return { width: round(width), height: round(height), body };
}

function lockupSvg(markColor: string, wordColor: string) {
  const g = lockupGroup(markColor, wordColor);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${g.width} ${g.height}">${g.body}</svg>`;
}

function ogSvg() {
  const W = 1200;
  const H = 630;
  const g = lockupGroup(colors.volt, colors.white);
  const scale = (W * 0.56) / g.width;
  const tx = round((W - g.width * scale) / 2);
  const ty = round((H - g.height * scale) / 2);
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">` +
    `<rect width="${W}" height="${H}" fill="${colors.ink}"/>` +
    `<g transform="translate(${tx} ${ty}) scale(${round(scale * 1000) / 1000})">${g.body}</g></svg>`
  );
}

// ---------------------------------------------------------------------------------------------
// Writers

function write(path: string, data: string | Buffer) {
  mkdirSync(dirname(out(path)), { recursive: true });
  writeFileSync(out(path), data);
  console.log(`  ${path}`);
}

function png(svg: string, width?: number): Buffer {
  return new Resvg(svg, width ? { fitTo: { mode: 'width', value: width } } : {}).render().asPng();
}

console.log('Brand assets:');

// Vector sources in the theme package.
write(
  'packages/theme/assets/mark.svg',
  markOnCanvas(120, 'currentColor', MARK_VISIBLE_WIDTH / 120),
);
write('packages/theme/assets/wordmark.svg', wordmarkSvg('currentColor'));
write('packages/theme/assets/lockup-on-dark.svg', lockupSvg(colors.volt, colors.white));
write('packages/theme/assets/lockup-on-light.svg', lockupSvg(colors.ink, colors.ink));

// App: icon (Volt, Ink mark ~64 %), Android adaptive icon (mark inside the 66 % safe zone), splash.
const APP = 'apps/mobile/assets/images';
write(`${APP}/icon.png`, png(markOnCanvas(1024, colors.ink, 0.64, colors.volt)));
write(`${APP}/android-icon-foreground.png`, png(markOnCanvas(1024, colors.ink, 0.54)));
write(
  `${APP}/android-icon-background.png`,
  png(
    `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024"><rect width="1024" height="1024" fill="${colors.volt}"/></svg>`,
  ),
);
write(`${APP}/android-icon-monochrome.png`, png(markOnCanvas(1024, colors.white, 0.54)));
// Splash: Volt mark on transparent; Ink background and width (~30 % of the screen) come from app.json.
write(`${APP}/splash-icon.png`, png(markOnCanvas(1024, colors.volt, 0.98)));
write(`${APP}/favicon.png`, png(markOnCanvas(48, colors.volt, 0.8, colors.ink, 10)));

// Web: favicon (svg + ico), apple-touch-icon, PWA icons (maskable: mark inside the 80 % safe circle), OG image.
const WEB = 'apps/web';
const faviconSvg = markOnCanvas(64, colors.volt, 0.8, colors.ink, 14);
write(`${WEB}/public/favicon.svg`, faviconSvg);
write(
  `${WEB}/src/app/favicon.ico`,
  await pngToIco([16, 32, 48].map((size) => png(faviconSvg, size))),
);
write(`${WEB}/public/apple-touch-icon.png`, png(markOnCanvas(180, colors.ink, 0.64, colors.volt)));
for (const size of [192, 512]) {
  write(`${WEB}/public/icon-${size}.png`, png(markOnCanvas(size, colors.ink, 0.56, colors.volt)));
}
write(`${WEB}/src/app/opengraph-image.png`, png(ogSvg()));

console.log('Done.');
