export interface StravaExerciseMatch {
  type: StravaExerciseType;
  /** `exact`: a table row; `pattern`: the generic type of its group; `generic`: nothing known. */
  quality: 'exact' | 'pattern' | 'generic';
}

/**
 * The Strava type for a library id or a custom exercise. Custom exercises use the row of the
 * library exercise they were copied from, then their movement pattern, then the generic entry.
 */
export function stravaExerciseType(
  exerciseId: string,
  custom?: Pick<CustomExercise, 'pattern' | 'basedOn'> | null,
): StravaExerciseMatch {
  const direct = STRAVA_EXERCISE_MAP[exerciseId];
  if (direct) return { type: direct, quality: 'exact' };
  const based = custom?.basedOn ? STRAVA_EXERCISE_MAP[custom.basedOn] : undefined;
  if (based) return { type: based, quality: 'exact' };
  if (custom && custom.pattern !== 'other') {
    return { type: STRAVA_PATTERN_FALLBACK[custom.pattern], quality: 'pattern' };
  }
  return { type: STRAVA_FALLBACK_TYPE, quality: 'generic' };
}
